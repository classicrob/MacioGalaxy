#!/usr/bin/env python3
"""Generate native/editor/runtime/field_names.inc: the known BCSV column names.

BCSV files store only hashes of their column names (TECH.md 1.2). The names come from the
decompilation's own string literals (every identifier-like literal in src/ and include/ that
the game could look up), plus a few the code builds at runtime. Our source, no disc data.

usage: python3 native/editor/tools/gen_field_names.py   (from the repository root)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LITERAL = re.compile(r'"([A-Za-z_][A-Za-z0-9_]{1,40})"')
# Built at runtime with snprintf or concatenation.
EXTRA = [f"Obj_arg{i}" for i in range(8)] + [f"point_arg{i}" for i in range(8)] + \
        [f"pnt{p}_{a}" for p in range(3) for a in "xyz"] + [f"ForceLowScenarioName{i}" for i in range(8)] + \
        [f"OpenCondition{i}" for i in range(3)] + [f"{k}_{a}" for k in ("pos", "dir", "scale") for a in "xyz"]


def jhash(name):
    value = 0
    for byte in name.encode("latin-1"):
        value = ((byte - 256 if byte >= 128 else byte) + value * 31) & 0xFFFFFFFF
    return value


def main():
    names = set(EXTRA)
    for path in list((ROOT / "src").rglob("*.cpp")) + list((ROOT / "include").rglob("*.hpp")):
        names.update(LITERAL.findall(path.read_text(errors="replace")))
    seen = {}
    for name in sorted(names):
        seen.setdefault(jhash(name), name)  # first (sorted) name wins a collision
    out = ROOT / "native/editor/runtime/field_names.inc"
    lines = ["// Generated by native/editor/tools/gen_field_names.py from the decompilation's string literals.",
             "// Candidate BCSV column names (hashed at first use). Do not edit."]
    names = sorted(seen.values())
    lines += [" ".join(f'"{n}",' for n in names[i:i + 8]) for i in range(0, len(names), 8)]
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(seen)} names -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
