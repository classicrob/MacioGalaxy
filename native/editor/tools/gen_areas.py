#!/usr/bin/env python3
"""Extract editor shape/manager metadata from the game's area factory and manager definitions."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
factory = (ROOT / 'src/Game/NameObj/NameObjFactory.cpp').read_text()
entries = re.findall(r'"([^"\n]+)"\s*,\s*create(CenterOriginCube|BaseOriginCube|Sphere|Bowl|BaseOriginCylinder)<\s*(\w+)\s*>', factory)
caps = re.findall(r'"([^"\n]+)"\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*createManager', (ROOT / 'src/Game/AreaObj/AreaObjContainer.cpp').read_text())
overrides = {}
for path in sorted((ROOT / 'include/Game').rglob('*.hpp')) + sorted((ROOT / 'src/Game/AreaObj').glob('*.cpp')):
    source = path.read_text(errors='replace')
    for cls, body in re.findall(r'class\s+(\w+)\s*:[^{]+\{(.*?)(?=\n};)', source, re.S):
        match = re.search(r'getManagerName\(\) const\s*\{\s*return\s+"([^"]+)"', body)
        if match:
            overrides[cls] = match[1]
    for cls, manager in re.findall(r'(\w+)::getManagerName\(\) const\s*\{\s*return\s+"([^"]+)"', source):
        overrides[cls] = manager
shapes = {'CenterOriginCube': 'Box', 'BaseOriginCube': 'BaseBox', 'Sphere': 'Sphere', 'Bowl': 'Bowl', 'BaseOriginCylinder': 'Cylinder'}
lines = ['// Generated by native/editor/tools/gen_areas.py from the game factory and managers.']
for name, shape, cls in entries:
    manager = overrides.get(cls, name)
    matches = [(n, int(c, 0)) for n, c in caps if manager.startswith(n)]
    if not matches:
        raise ValueError(f'No manager for {name}: {manager}')
    manager, capacity = matches[0]
    kind = 'Camera' if manager == 'CubeCamera' else 'Death' if manager in ('DeathArea', 'DarkMatterCube', 'DarkMatterCylinder') else 'Water' if manager == 'Water' else 'Switch' if manager == 'SwitchArea' else 'Message' if manager == 'MessageArea' else 'Other'
    lines.append(f'{{"{name}", "{manager}", Shape::{shapes[shape]}, Kind::{kind}, {capacity}}},')
(ROOT / 'native/editor/areas/definitions.inc').write_text('\n'.join(lines) + '\n')
